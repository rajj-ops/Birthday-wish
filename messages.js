window.renderFinalLetterDynamic = function() {
  const modeKey = window.isFlirtModeOn ? 'flirt' : 'normal';
  const langKey = window.selectedLang || 'od';
  const data = (letterData[modeKey] && letterData[modeKey][langKey]) 
                ? letterData[modeKey][langKey] 
                : letterData['normal']['od'];

  const headerEl = document.getElementById('macosFileTitle') || document.querySelector('.macos-title');
  const dearEl = document.getElementById('letterDearTitle');
  const p1 = document.getElementById('letterPara1');
  const p2 = document.getElementById('letterPara2');
  const p3 = document.getElementById('letterPara3');
  const prop = document.getElementById('letterProposalLine');

  if (headerEl) headerEl.innerText = data.header;
  if (dearEl) dearEl.innerHTML = data.dearTitle;
  if (p1) p1.innerText = data.p1;
  if (p2) p2.innerText = data.p2;
  if (p3) p3.innerText = data.p3 + "\n\n" + data.p4;
  if (prop) prop.innerHTML = `<span style="color:#ff2a5f; font-weight:700;">${data.proposal}</span>`;
};
